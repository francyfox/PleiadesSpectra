import { defineConfig } from "wxt";

/**
 * User scripts only run on sites the extension has host permission for: without it a script registers
 * fine and then never runs. The content script already reads every page, so this asks for nothing new.
 */
const ALL_SITES = "*://*/*";

/** The local server: the camera stream, the agent bridge and the online check. */
/** The picture of Beta is drawn by the content script on any site, so pages must be allowed to load it. */
const PICTURE_RESOURCES = ["beta_plugin.webp", "beta/*.webp"];

const AGENT_SERVER_ORIGIN = "http://localhost:3001/*";

/** What the browsers show in their list of extensions; without it the name would be the package name, `@repo/wxt`. */
const EXTENSION_NAME = "Pleiades Spectra";
/** The Chrome Web Store rejects a description longer than 132 characters. */
const EXTENSION_DESCRIPTION =
	"Your face as a remote control for web pages: scripts react to gestures, pulse and breathing read by the SmartSpectra SDK.";

/**
 * Firefox needs an add-on id to keep its storage and to be signed, and since version 140 a statement of what data the
 * extension collects. The camera picture goes to the local server only and is never kept, so it collects none.
 * 140 is the first Firefox version that knows that statement.
 */
const FIREFOX_SETTINGS = {
	gecko: {
		id: "pleiades-spectra@spectra.local",
		strict_min_version: "140.0",
		data_collection_permissions: { required: ["none"] },
	},
};

// Aliases: `@/` and `~/` → src, `@@/` and `~~/` → apps/wxt (generated by WXT from srcDir).
// See https://wxt.dev/api/reference/wxt/interfaces/inlineconfig.html
export default defineConfig({
	srcDir: "src",
	/**
	 * The scripts are registered with the Manifest V3 form of the `userScripts` API (an array, `worldId`,
	 * `configureWorld`, `getScripts`). Firefox has only an older, different API under Manifest V2, which WXT builds
	 * for Firefox by default, so both browsers are built as V3.
	 */
	manifestVersion: 3,
	manifest: ({ browser, command }) => {
		/** Only the dev server needs to look at open tabs, to reuse the blank one and reopen the test page. */
		const devPermissions = command === "serve" ? ["tabs"] : [];
		const common = {
			name: EXTENSION_NAME,
			description: EXTENSION_DESCRIPTION,
			host_permissions: [AGENT_SERVER_ORIGIN, ALL_SITES],
			web_accessible_resources: [
				{ resources: PICTURE_RESOURCES, matches: [ALL_SITES] },
			],
		};
		return browser === "firefox"
			? {
					...common,
					permissions: ["storage", ...devPermissions],
					optional_permissions: ["userScripts"],
					browser_specific_settings: FIREFOX_SETTINGS,
				}
			: {
					...common,
					permissions: [
						"storage",
						"userScripts",
						"offscreen",
						...devPermissions,
					],
				};
	},
	vite: () => ({
		// TSX compiles to HTML strings via @kitajs/html; Alpine makes them interactive.
		oxc: { jsx: { runtime: "automatic", importSource: "@kitajs/html" } },
		// The test bench links to the demo app; `DEMO_PORT` moves both (apps/demo reads the same variable).
		define: {
			"import.meta.env.WXT_DEMO_PORT": JSON.stringify(
				process.env.DEMO_PORT ?? "4010",
			),
		},
	}),
});
